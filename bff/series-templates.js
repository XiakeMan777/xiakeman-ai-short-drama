function sanitizeSeriesSourceTerms(value) {
  if (typeof value === 'string') {
    return SERIES_SOURCE_TERM_REWRITES.reduce(
      (text, [pattern, replacement]) => text.replace(pattern, replacement),
      value,
    );
  }
  if (Array.isArray(value)) {
    return value.map(sanitizeSeriesSourceTerms);
  }
  if (!value || typeof value !== 'object') {
    return value;
  }
  const cleaned = {};
  Object.entries(value).forEach(([key, nested]) => {
    cleaned[key] = sanitizeSeriesSourceTerms(nested);
  });
  return cleaned;
}

function prepareSeriesPromptData(value) {
  return sanitizeSeriesSourceTerms(stripGeneratedEpisodeDrafts(value));
}

function dedupePromptLines(lines) {
  const seen = new Set();
  return lines.filter((line) => {
    if (typeof line !== 'string') return true;
    const normalized = line.trim();
    if (!normalized) return true;
    if (seen.has(normalized)) return false;
    seen.add(normalized);
    return true;
  });
}

