function normalizeGuardText(value) {
  if (typeof value !== 'string') return '';
  try {
    return JSON.stringify(prepareSeriesPromptData(JSON.parse(value)));
  } catch {
    return sanitizeSeriesSourceTerms(value);
  }
}

function findBoundaryLeakIssues(scriptText) {
  const issues = [];
  const lines = scriptText.split(/\r?\n/);
  lines.forEach((line, index) => {
    if (!line.includes('本镜不提前')) return;
    if (!/(?:不引出|不出现|不进入|不展开|不提前抛出|不提前亮出)/.test(line)) return;
    const leakedTerms = SERIES_SCRIPT_HIGH_RISK_TERMS.filter((term) => line.includes(term));
    leakedTerms.forEach((term) => {
      const appearsElsewhere = lines.some((otherLine, otherIndex) => (
        otherIndex !== index
        && !otherLine.includes('本镜不提前')
        && otherLine.includes(term)
      ));
      if (appearsElsewhere) {
        issues.push(`自写边界“本镜不提前”禁止引出 ${term}，正文后续又写了 ${term}`);
      }
    });
  });
  return issues;
}

function findSeriesEpisodeScriptGuardIssues(scriptText, rawUserContent = '') {
  const text = typeof scriptText === 'string' ? scriptText : '';
  if (!text.trim()) return ['生成剧本为空'];

  const inputText = normalizeGuardText(rawUserContent);
  const issues = [];

  const inventedTerms = SERIES_SCRIPT_HIGH_RISK_TERMS.filter((term) => text.includes(term) && !inputText.includes(term));
  if (inventedTerms.length > 0) {
    issues.push(`出现输入未给出的高风险古偶素材：${inventedTerms.join('、')}`);
  }

  if (SERIES_SCRIPT_TEMPLATE_BLEED_RE.test(text)) {
    issues.push('同一集堆入“短刀”与“凤冠/血书/染血旧簪”等模板化古偶道具');
  }

  if (SERIES_SCRIPT_BACKSTAGE_SECTION_RE.test(text)) {
    issues.push('生成稿含后台说明块：分镜职责与边界/角色与连续性/人设锁定/道具状态/自检等必须删除');
  }

  if (SERIES_SCRIPT_TEMPORARY_NAMED_SERVANT_RE.test(text)) {
    const inventedServants = SERIES_SCRIPT_TEMPORARY_SERVANT_NAMES
      .filter((name) => text.includes(name) && !inputText.includes(name));
    if (inventedServants.length > 0) {
      issues.push(`临时小厮/宫人被命名：${inventedServants.join('、')}；除非系列圣经已列为常驻角色，否则要写成群体或职能称呼`);
    }
  }

  if (SERIES_SCRIPT_PALACE_POWER_PROP_RE.test(text) && !SERIES_SCRIPT_PALACE_POWER_BOUNDARY_RE.test(text)) {
    issues.push('宫廷权力边界不清：出现圣旨/懿旨/白绫/冷宫/宫规等元素时，必须写清谁越权、谁只能押、谁要担责');
  }

  if (SERIES_SCRIPT_NEXT_RELAY_POSITION_CONFLICT_RE.test(text)) {
    issues.push('接下一镜人物位置矛盾：角色仍在院中/石桌边时，不得让屋内/门后同时出现由他触发的练剑声或破风声');
  }

  issues.push(...findBoundaryLeakIssues(text));
  return issues;
}

