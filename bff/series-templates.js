function stripGeneratedEpisodeDrafts(value) {
  if (Array.isArray(value)) {
    return value.map(stripGeneratedEpisodeDrafts);
  }
  if (!value || typeof value !== 'object') {
    return value;
  }
  const cleaned = {};
  Object.entries(value).forEach(([key, nested]) => {
    if (key === 'generatedScript' || key === 'generatedAt') return;
    cleaned[key] = stripGeneratedEpisodeDrafts(nested);
  });
  return cleaned;
}

