4. **结尾段禁止泄力**
   - 每镜最后一段禁止用长段背景交代、成长回忆、平缓自述来泄力
   - 最后一段必须停在挑衅、拆穿、威胁、决定、翻转、关系撕裂、危险逼近中的至少一种

5. **静态动作从严压缩**
   - 嗑瓜子、敲桌角、发呆、沉默、抬眼、站着不动这类静态动作，只有在能强化挑衅、压迫或反差时才保留
   - 如果静态动作不能制造压力，就删掉
   - 同一种静态动作在同一镜里不要反复机械重复，除非它形成明确升级

