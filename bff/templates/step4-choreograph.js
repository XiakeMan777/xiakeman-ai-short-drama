function applyFrameRulesToChoreographPrompt(prompt, sceneType, videoRatio) {
  const frameRatio = normalizeFrameRatio(videoRatio);
  const frameRules = buildFrameDirectorRules(frameRatio);
  const frameLabel = getFrameLanguageLabel(frameRatio);
  const productionLabel = getFrameProductionLabel(frameRatio);
  let next = prompt
    .replace('专门为竖屏短剧设计打斗场景的动作编排', `专门为${productionLabel}设计打斗场景的动作编排`)
    .replace(/### 5\. 运镜配合打斗（竖屏9:16适配，快节奏优先）/, `### 5. 运镜配合打斗（${frameLabel}适配，快节奏优先）`)
    .replace(/### 4\. 竖屏9:16适配/, `### 4. ${frameLabel}适配`)
    .replace(/### 3\. 竖屏9:16适配/, `### 3. ${frameLabel}适配`)
    .replace(/竖屏9:16/g, frameLabel);

  if (frameRatio === '16:9') {
    next = next
      .replace('- 对话双方一上一下或一前一后布局\n- 特写时人物占画面1/2~2/3\n- 避免双人并排（竖屏太窄）',
        '- 允许双人并排、桌边对坐、二人同框和三角构图，优先明确左右关系与视线方向\n- 可使用过肩反打、侧面双人中景、横向座位关系和前景遮挡，但说话人口型必须清晰\n- 特写仍可使用，但不要把横屏压成竖向窄柱；听话人可在同框中保留反应')
      .replace('- 纵向运镜作为转场手段（上推/下拉）\n- 利用竖屏纵深空间做匹配剪辑\n- 空镜头优先竖屏构图（建筑/天空/道路的纵向延伸）',
        '- 允许横向转场、横摇揭示、侧向跟拍进入新空间和宽景建立场景\n- 利用横屏前中后景、门窗/走廊/桥面等横向空间做匹配剪辑\n- 空镜头可以展示完整横向空间，但必须服务下一段人物入场或情绪承接')
      .replace('- 对攻近景：快速跟拍 + 震屏(screen shake)',
        '- 对攻近景：快速跟拍 + 震屏(screen shake)\n- 横屏攻防线：画面左/右形成清晰攻防关系，允许宽幅横移、横摇和侧向跟拍保持连续动作\n- 横向追逐/闪避：角色可从左到右或右到左穿越画面，必须写清起点、路径、终点和安全区')
      .replace('- 闪避反击：快速平移 + 硬切(hard cut)',
        '- 闪避反击：快速平移 + 硬切(hard cut)，横屏可用侧向跟拍保留双方同框')
      .replace('- 群战混战：手持晃动(handheld) + 快剪(flash cut)≤1秒',
        '- 群战混战：手持晃动(handheld) + 快剪(flash cut)≤1秒；横屏可用宽景建立多人同框，再切中近景锁主动作')
      .replace(/纵向运镜/g, '横向/纵深运镜')
      .replace(/竖屏构图/g, '横屏构图')
      .replace(/竖屏纵深空间/g, '横屏纵深空间');
  }

  return `${next}\n\n${frameRules}`;
}

/** 构建 choreograph 步骤的 system prompt（根据场景类型选择路径） */
function buildChoreographSystemPrompt(sceneType, combatSubType, videoRatio) {
  switch (sceneType) {
    case 'combat': {
      const combatPrompt = applyFrameRulesToChoreographPrompt(CHOREOGRAPH_COMBAT_SYSTEM_PROMPT, sceneType, videoRatio);
      if (combatSubType === 'suppressed') {
        return combatPrompt + `\n\n## ⚠️ 当前为被动压制型打斗（combatSubType=suppressed）\n你必须在编排时严格遵循"被动压制型打斗子路径"（见上方⚠️标注），使用"压迫递增→临界闪避→反击蓄势→定格悬念"4拍结构。禁止使用标准打斗的"蓄势→交锋→高潮→收束"结构，因为被压制方没有主动攻击能力，标准4拍会导致全程静态叙事。核心原则：被动方的每次闪避/格挡都必须写得像主动攻击一样有速度感和力量感，每个时间段必须有至少一次微型攻防回合（敌方出招→被动方闪避/格挡→视觉反馈），而非"持续被压→继续被压"。`;
      }
      return combatPrompt;
    }
    case 'dialogue':
      return applyFrameRulesToChoreographPrompt(CHOREOGRAPH_DIALOGUE_SYSTEM_PROMPT, sceneType, videoRatio);
    case 'emotional':
      return applyFrameRulesToChoreographPrompt(CHOREOGRAPH_EMOTIONAL_SYSTEM_PROMPT, sceneType, videoRatio);
    case 'transition':
      return applyFrameRulesToChoreographPrompt(CHOREOGRAPH_TRANSITION_SYSTEM_PROMPT, sceneType, videoRatio);
    default:
      return applyFrameRulesToChoreographPrompt(CHOREOGRAPH_DIALOGUE_SYSTEM_PROMPT, sceneType, videoRatio);
  }
}

