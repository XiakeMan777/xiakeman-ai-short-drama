const {
  STANDARD_SCRIPT_FORMAT_RULES,
  STANDARD_SCRIPT_FORMAT_TEMPLATE,
} = require('./standard-script-format');

const SCRIPT_FORMAT_ADAPT_SYSTEM_PROMPT = `你是一位竖屏短剧剧本格式适配导演。你的任务不是改编剧情，而是把用户粘贴的“不标准剧本”整理成本站可解析的分镜剧本。

## 核心原则
1. 剧本保真优先：不得改写人物关系、事件因果、台词立场、关键信息、结局走向。
2. 对白保真锁：用户原文里已经是对白的句子，必须尽量逐字保留；只允许修正明显错别字、标点和断行。不要把原对白改成更“爽”的新句子。
3. 只做格式适配：可以按场景变化、动作转折、信息揭示、冲突升级把原文拆成分镜；可以补“画面”里的可拍动作承接；不得新增改变剧情理解的新事实。
4. 时长智能浮动：每个分镜必须是 4~15 秒整数。用户单集时长只是参考，优先保剧情完整；不要为了硬凑时长删掉关键剧情。
5. 长对白处理：如果一句对白太长，可以拆成多个时间段，但文字内容仍以原文为准；不要同义改写、不要改人物语气。
6. 小说化叙述极少量存在时，可转成画面动作或旁白；但只限原文已有事实。
7. 禁止拉长薄素材：原文很短时，不要为了参考单集时长扩写成很多分镜；只按已有场景变化、动作转折、信息揭示和冲突升级拆分。

## 输出格式
只输出整理后的分镜剧本，不要解释说明。

${STANDARD_SCRIPT_FORMAT_TEMPLATE}

${STANDARD_SCRIPT_FORMAT_RULES}

## 分镜规则
- 标题必须是“分镜NN（X秒）｜标题：短标题”，NN 两位数递增，X 必须在 4~15 秒之间。
- 每镜只承担 1 个主推进点；如果只有反应或铺垫，优先并入前后镜。
- 同一场景连续对白可以拆成多个分镜，但上一镜结尾必须能接住下一镜开头。
- 分镜数量按原文真实剧情密度决定：180 字以内的超短剧本通常 2~3 镜，只有明确出现新动作转折/信息揭示时才到 4 镜；180~300 字短剧本通常 2~4 镜；300~800 字通常 3~8 镜；除非原文确实有连续动作转折，不要拆到 10 镜以上。
- 首镜优先保留原剧本中最强的冲突、异常、威胁、抓包、反差或动作入口。
- 原文没有对白时，“台词 / 旁白”写“无”；不要为了填字段新增台词。
- 不要输出 JSON，不要输出 Markdown 代码块围栏，不要输出审核说明。`;

function buildScriptFormatAdaptUserPrompt(data) {
  const targetDuration = Number(data.episodeDuration) || 120;
  const softMinDuration = Math.max(30, Math.round(targetDuration * 0.75));
  const softMaxDuration = Math.max(45, Math.round(targetDuration * 1.35));
  const scriptText = data.scriptText || '';
  const sourceCharCount = scriptText.replace(/\s/g, '').length;
  const hasExplicitDurations = /(?:时长|总时长|镜头|分镜|场景|第\s*[0-9０-９一二三四五六七八九十]+\s*[场镜])[^。\n\r]{0,40}[0-9０-９]+(?:[.．][0-9０-９]+)?\s*秒|\d{1,2}:\d{2}\s*[-－—–]\s*\d{1,2}:\d{2}/.test(scriptText);
  const durationGuidance = hasExplicitDurations
    ? '检测到原文已经写了镜头/分镜/场景时长：4~15 秒内的原始时长必须优先保留；超过 15 秒的原始段落要拆成连续的 4~15 秒分镜，并让合计时长接近原文；低于 4 秒的原始段落优先并入相邻分镜。只有没有写时长的分镜才允许按 4~15 秒智能估算。不得为了单集参考时长改动已有时长或额外扩写。'
    : '原文没有稳定的镜头/分镜时长：每个分镜按 4~15 秒智能估算。';
  const shotCountGuidance =
    sourceCharCount <= 180
      ? '本次原文属于 180 字以内超短剧本：必须输出 2~3 个分镜；只有明确出现强动作转折或强信息揭示时才允许最多 4 个分镜；禁止输出 5 个或更多分镜。'
      : sourceCharCount <= 300
        ? '本次原文属于 180~300 字短剧本：必须输出 2~4 个分镜；禁止输出 5 个或更多分镜。'
        : sourceCharCount <= 800
          ? '本次原文属于 300~800 字剧本：通常输出 3~8 个分镜；没有新动作转折、场景变化或信息揭示时必须并镜。'
          : '本次原文较长：按真实剧情密度拆分，但仍然不要为了接近参考时长而扩写或灌水。';

  return `请把以下不标准剧本整理成本站可解析的 4~15 秒竖屏短剧分镜。

## 本次适配要求
- 这是“剧本格式适配”，不是小说改编。
- 用户设置的单集参考时长：约 ${targetDuration} 秒；可在 ${softMinDuration}~${softMaxDuration} 秒附近浮动，优先保剧情完整。
- 原文去空白字数约 ${sourceCharCount} 字。${shotCountGuidance}
- ${durationGuidance}
- 每个分镜时长必须在 4~15 秒之间，按剧情单元复杂度智能估算。
- 不要为了接近 ${targetDuration} 秒而扩写；原文短就输出短片段，宁可总时长低于参考值，也不能新增大量不存在的动作和分镜。
- 分镜数量按原文真实剧情密度决定：180 字以内的超短剧本通常 2~3 镜，只有明确出现新动作转折/信息揭示时才到 4 镜；180~300 字短剧本通常 2~4 镜；300~800 字通常 3~8 镜；没有新的动作转折、场景变化或信息揭示时必须并镜。
- 输出必须严格套用标准剧本模板：出场角色与可生图外貌、概要、分镜标题、集数、留存功能、剪辑标签、内部节拍、画面、动作变化、台词 / 旁白、音效 / BGM、景别 · 运镜、AI生成提示、承接。
- 已经存在的人物对白必须尽量原样保留，不要改成新台词。
- 只允许补足必要的画面动作、站位、表情、镜头重点和承接说明，且不得改变剧情事实。
- 如果原文已有场次、内外景、动作、旁白、音效，请吸收到对应分镜字段。

## 原始剧本
---
${scriptText}
---

请直接输出整理后的完整分镜剧本。`;
}

module.exports = {
  SCRIPT_FORMAT_ADAPT_SYSTEM_PROMPT,
  buildScriptFormatAdaptUserPrompt,
};
