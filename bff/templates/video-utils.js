function buildVideoPromptCompactUserPrompt(data) {
  const ratio = typeof data.targetCompressionRatio === 'number' ? data.targetCompressionRatio : 0.55;
  const percent = Math.round(ratio * 100);
  const targetMaxChars = typeof data.targetMaxChars === 'number' ? data.targetMaxChars : 1950;
  const aggressiveMode = data.aggressiveMode === true;
  const attempt = typeof data.attempt === 'number' ? data.attempt : 1;

  return `请压缩以下视频提示词，使其更适合视频模型消费。

## 压缩目标
- 目标长度：尽量压缩到原文的 ${percent}% 左右，且最终必须不超过 ${targetMaxChars} 字
- 优先压缩：场景 / 人物 / 道具中已经被参考图锁定的重复外观与环境细节
- 严格保留：参考图编号、7段结构、时间段、台词原文、运镜推进、朝向、动作起止、落幅定格

## 额外要求
- 如果原文包含“故事板导演参考图”约束，必须保留其导演参考作用，但可以改写成更紧凑的表达。
- 如果原文已经很短，不要为了压缩而删掉镜头关键逻辑；以“去重复、保结构”为第一原则。
- 如果原文包含“Seedance 2.0 素材角色表”，可压缩为短表，但必须保留每个参考图片编号的素材职责。
- 当前是第 ${attempt} 次压缩。${aggressiveMode ? '这一次必须进一步激进压缩：优先继续砍掉场景、人设、光影中的重复修辞，把时间段保留为动作骨架，不要保留细枝末节。' : '优先做结构保真的第一轮压缩。'}
- 如果你的输出仍然会超过 ${targetMaxChars} 字，请继续删减冗余修辞，直到满足上限，再输出最终版本。

## 原始提示词
${data.sourcePrompt}

现在直接输出压缩后的最终提示词。`;
}

